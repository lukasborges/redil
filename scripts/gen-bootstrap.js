#!/usr/bin/env node
/**
 * Generates bootstrap.js, the file index.html loads as its microloader.
 *
 * Sencha Cmd normally produces it. Sencha Cmd 6.6.0.13 is no longer obtainable,
 * so this script writes a replacement that boots the app straight from the
 * Ext JS build already vendored in ext/ and the theme CSS already compiled in
 * ext/packages/. That makes `npm start` work with nothing but npm installed.
 *
 * The custom theme's Sass is gone with the rest of the Sencha Cmd scaffolding.
 * The app loads the stock ext-theme-crisp CSS that the theme used to extend, and
 * then resources/css/redil-theme.css restates the original look as plain CSS on
 * top. All that survives of the theme package is Font Awesome and the two lines
 * of overrides/theme-init.js that name the theme.
 */

'use strict';

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');

const STYLESHEETS = [
	'ext/packages/ext-theme-crisp/build/resources/ext-theme-crisp-all-debug.css',
	'resources/fonts/font-awesome/css/font-awesome.css',
	// The app's own look, layered over crisp.
	'resources/css/redil-theme.css',
	// The modernisation pass. Drop this line to get the original look back.
	'resources/css/redil-modern.css',
];

const FRAMEWORK = ['ext/build/ext-all-rtl-debug.js'];

/**
 * Loaded after the framework. Ext.Loader resolves everything under app/ on its
 * own, so only files it cannot discover by class name belong here: the theme
 * marker, the Ext.override calls, the loose renderer helper, and app.js last
 * because it calls Ext.application.
 */
const THEME_MARKER = 'overrides/theme-init.js';

function filesAfterFramework() {
	return [
		// First, and filtered out below, because collectScripts walks the same
		// directory and would otherwise load it a second time.
		THEME_MARKER,
		...collectScripts('overrides').filter(file => file !== THEME_MARKER),
		// A browser library the renderer used to require. With contextIsolation
		// there is no require in the page, so it is loaded as what it already is:
		// a script that defines window.Mousetrap. electron-builder keeps
		// node_modules in the asar, so this path holds in a packaged build too.
		'node_modules/mousetrap/mousetrap.js',
		// Ext.ux classes the app pulls in by xtype or plugin alias. Preloaded
		// because Ext.Loader would otherwise resolve them with a synchronous
		// XMLHttpRequest, which Chromium refuses on file:// URLs.
		'ext/src/ux/BoxReorderer.js',
		'ext/src/ux/TabReorderer.js',
		'ext/src/ux/statusbar/StatusBar.js',
		'resources/js/loadscreen.js',
		'app.js',
	];
}

function collectScripts(dir, found = []) {
	for (const entry of fs.readdirSync(path.join(root, dir), { withFileTypes: true })) {
		const relative = dir + '/' + entry.name;
		if (entry.isDirectory()) collectScripts(relative, found);
		else if (entry.name.endsWith('.js')) found.push(relative);
	}
	return found;
}

function render(stylesheets, framework, rest) {
	return `// GENERATED by scripts/gen-bootstrap.js - do not edit by hand.
// Replaces the Sencha Cmd microloader. Run \`npm run bootstrap\` to regenerate.
(function () {
	var STYLESHEETS = ${JSON.stringify(stylesheets)};
	var FRAMEWORK = ${JSON.stringify(framework)};
	var REST = ${JSON.stringify(rest)};

	function addStylesheet(href) {
		var link = document.createElement('link');
		link.rel = 'stylesheet';
		link.href = href;
		document.head.appendChild(link);
	}

	function loadInOrder(sources, done) {
		var next = 0;
		(function loadNext() {
			if (next >= sources.length) return done();
			var script = document.createElement('script');
			script.src = sources[next++];
			script.onload = loadNext;
			script.onerror = function () {
				console.error('bootstrap: could not load ' + script.src);
				loadNext();
			};
			document.head.appendChild(script);
		})();
	}

	function pointLoaderAtSources() {
		Ext.Loader.setConfig({
			enabled: true,
			disableCaching: false,
			paths: { Redil: 'app', Ext: 'ext/src' }
		});
	}

	// Deferred to DOMContentLoaded because index.html injects the translation
	// file, which defines the global \`locale\`, after this script tag. Model
	// classes read locale[...] while they are being defined.
	function boot() {
		STYLESHEETS.forEach(addStylesheet);
		loadInOrder(FRAMEWORK, function () {
			pointLoaderAtSources();
			loadInOrder(REST, function () {});
		});
	}

	document.readyState === 'loading'
		? document.addEventListener('DOMContentLoaded', boot)
		: boot();
})();
`;
}

const contents = render(STYLESHEETS, FRAMEWORK, filesAfterFramework());
fs.writeFileSync(path.join(root, 'bootstrap.js'), contents);
console.log('bootstrap.js written');
